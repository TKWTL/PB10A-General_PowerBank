#!/usr/bin/env python3
"""Generate the integer SW6306 NTC table from R25 and the Beta model."""

import argparse
import math
from pathlib import Path


def make_header(r25, beta, min_c, max_c, step_c):
    if r25 <= 0 or beta <= 0:
        raise ValueError("R25 and Beta must be positive")
    if not -273 <= min_c < max_c <= 3276 or step_c <= 0 or (max_c - min_c) % step_c:
        raise ValueError("temperature range must be representable and evenly divided by the step")

    ohms = []
    for temp_c in range(min_c, max_c + 1, step_c):
        exponent = beta * (1 / (273.15 + temp_c) - 1 / 298.15)
        ohms.append(int(r25 * math.exp(exponent) + 0.5))

    if ohms[-1] < 1 or ohms[0] * 80 > 0xFFFFFFFF:
        raise ValueError("table resistance is outside the firmware's 32-bit range")
    for cold, hot in zip(ohms, ohms[1:]):
        span_uv = (cold - hot) * 80
        if span_uv <= 0 or span_uv * step_c * 10 + span_uv // 2 > 0xFFFFFFFF:
            raise ValueError("table interval cannot be interpolated with 32-bit arithmetic")

    return "\n".join(
        [
            f"/* Generated by gen_ntc_table.py for R25={r25} ohms, B={beta} K. */",
            "#ifndef SW6306_NTC_TABLE_H",
            "#define SW6306_NTC_TABLE_H",
            "",
            "#include <stdint.h>",
            "",
            f"#define SW6306_NTC_TABLE_MIN_C10 ({min_c * 10})",
            f"#define SW6306_NTC_TABLE_STEP_C10 {step_c * 10}u",
            "",
            "static const uint32_t sw6306_ntc_ohms[] = {",
            *(f"    {resistance}u," for resistance in ohms),
            "};",
            "",
            "#endif",
            "",
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--r25", type=int, default=10000, help="resistance at 25 °C, in ohms")
    parser.add_argument("--beta", type=int, default=3380, help="Beta value, in kelvins")
    parser.add_argument("--min-c", type=int, default=-40)
    parser.add_argument("--max-c", type=int, default=125)
    parser.add_argument("--step-c", type=int, default=5)
    parser.add_argument("--check", action="store_true", help="check the header instead of writing it")
    args = parser.parse_args()
    try:
        header = make_header(args.r25, args.beta, args.min_c, args.max_c, args.step_c)
    except (OverflowError, ValueError) as error:
        parser.error(str(error))

    path = Path(__file__).with_name("sw6306_ntc_table.h")
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != header:
            parser.error("sw6306_ntc_table.h differs from the generated table")
    else:
        path.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
