void I18N_SetLanguage(i18n_language_t language) {
    s_language = language;
}

i18n_language_t I18N_GetLanguage(void) {
    return s_language;
}

const char *I18N_Text(const char *english_key) {
    if (!english_key)
        return "";
    if (s_language == I18N_LANG_ZH_CN) {
        unsigned lo = 0u, hi = sizeof(s_catalog) / sizeof(s_catalog[0]);
        while (lo < hi) {
            unsigned mid = lo + (hi - lo) / 2u;
            int cmp = strcmp(english_key, s_catalog[mid].en);
            if (!cmp)
                return s_catalog[mid].zh;
            if (cmp < 0)
                hi = mid;
            else
                lo = mid + 1u;
        }
    }
    return english_key;
}
