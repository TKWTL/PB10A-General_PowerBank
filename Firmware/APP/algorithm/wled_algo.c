/* PB10A: measured continuous power/temperature envelope and SOS budget.
 * Keep the existing 10 ms service and external-load/meter ownership. */
#include "wled_algo.h"
#include "power_algo.h"
#include "tim.h"
#include <stddef.h>

#define WLED_MIN_LEVEL 1u
#define WLED_START_PRESS_LIMIT 2u
#define WLED_PWM_MAX 1023u
#define WLED_RAMP_MS 160u
#define WLED_TEST_AMBIENT_C10 300
#define WLED_TARGET_C10 700
#define WLED_STOP_C10 780
#define WLED_RESTART_C10 650
#define WLED_HYST_C10 20
#define WLED_RECOVER_MS 5000u
#define SOS_UNIT_MS 100u
#define SOS_ON_MS 1500u
#define SOS_TRANSMIT_MS 2700u
#define SOS_MIN_CYCLE_MS 5000u
#define SOS_MIN_BUDGET_MW 1200u

/* Thermal-camera measurements at 30 C. Interpolate in PWM compare/power,
 * not brightness percentage. No thermal time constant has been measured. */
typedef struct {
    uint16_t mw, rise_c10;
} wled_point_t;

static const wled_point_t s_points[] = {
    {0u, 0u},
    {1346u, 280u},
    {3208u, 450u},
    {7023u, 950u},
};

static int8_t s_step_request;
static uint8_t s_raise_limit, s_sos_request, s_sos, s_active;
static uint8_t s_level, s_output_level;
static uint8_t s_manual_cap, s_cap_valid, s_thermal_blocked;
static uint8_t s_limit_now, s_limit_recover, s_ref_measured;
static int16_t s_ref_temp, s_release_temp;
static uint8_t s_sos_paused;
static uint16_t s_pwm, s_ramp_from, s_target;
static uint32_t s_wait_at, s_ramp_at, s_recover_at;
static uint32_t s_sos_at, s_sos_cycle_ms;
static uint16_t s_sos_budget_mw;
static wled_sos_state_t s_sos_state;

static uint16_t wled_level_to_pwm(uint8_t level) {
    uint16_t pwm = (uint16_t)(level * level);
    return pwm > WLED_PWM_MAX ? WLED_PWM_MAX : pwm;
}

/* Generated by linear interpolation at compare L*L between the
 * measured points 0, 64, 256 and 576. Avoid division in the 10 ms loop. */
static const uint16_t s_manual_power_mw[] = {
    0u, 21u, 84u, 189u, 336u, 525u, 757u, 1030u, 1346u, 1510u,
    1695u, 1898u, 2121u, 2364u, 2626u, 2907u, 3208u, 3601u, 4018u, 4459u};

static uint16_t level_power_mw(uint8_t level) {
    return level <= WLED_MANUAL_MAX_LEVEL ? s_manual_power_mw[level] : WLED_SOS_PEAK_MW;
}

static uint16_t rise_at_power(uint16_t mw) {
    if (!mw)
        return 0u;
    for (unsigned i = 1u; i < sizeof(s_points) / sizeof(s_points[0]); ++i) {
        const wled_point_t *a = &s_points[i - 1u], *b = &s_points[i];
        if (mw <= b->mw) {
            uint32_t span = b->mw - a->mw;
            /* Round temperature rise upward, conservatively. */
            return (uint16_t)(a->rise_c10 +
                              ((uint32_t)(mw - a->mw) * (b->rise_c10 - a->rise_c10) + span - 1u) / span);
        }
    }
    return s_points[3].rise_c10;
}

/* Maximum continuous power predicted to reach 70 C at this ambient.
 * The ambient floor prevents extrapolating to higher output at <30 C. */
static uint16_t ambient_power_budget(int16_t ambient) {
    int32_t rise = WLED_TARGET_C10 - (int32_t)ambient;
    if (rise <= 0)
        return 0u;
    for (unsigned i = 1u; i < sizeof(s_points) / sizeof(s_points[0]); ++i) {
        const wled_point_t *a = &s_points[i - 1u], *b = &s_points[i];
        if (rise <= b->rise_c10)
            return (uint16_t)(a->mw + (uint32_t)(rise - a->rise_c10) * (b->mw - a->mw) /
                                          (b->rise_c10 - a->rise_c10));
    }
    return s_points[3].mw;
}

static uint8_t hotspot_manual_limit(int16_t temp) {
    if (temp <= 550)
        return WLED_MANUAL_MAX_LEVEL;
    if (temp <= 600)
        return 17u;
    if (temp <= 650)
        return 16u;
    if (temp <= 700)
        return 15u;
    if (temp <= 730)
        return 12u;
    if (temp < WLED_STOP_C10)
        return 8u;
    return 0u;
}

static uint16_t hotspot_sos_budget(int16_t temp) {
    if (temp <= 550)
        return 2500u;
    if (temp <= 600)
        return 2200u;
    if (temp <= 650)
        return 1800u;
    if (temp < 750)
        return 1200u;
    return 0u;
}

/* The measured MCU and battery temperatures follow room ambient, not
 * the LED hotspot. Use the hotter valid reference and the test floor. */
static uint8_t thermal_reference(int16_t *temp, uint8_t *measured) {
#ifdef WLED_READ_HOTSPOT_C10
    if (WLED_READ_HOTSPOT_C10(temp)) {
        *measured = 1u;
        return 1u;
    }
#endif
    int16_t ntc;
    int mcu;
    uint8_t mcu_valid;
    uint8_t ntc_valid = PowerAlgo_GetExtLoadTemperature(&ntc);
    PowerAlgo_GetSystemAdc(NULL, &mcu, &mcu_valid);
    *measured = 0u;
    *temp = WLED_TEST_AMBIENT_C10;
    if (ntc_valid && ntc > *temp)
        *temp = ntc;
    if (mcu_valid && mcu > *temp)
        *temp = (int16_t)mcu;
    return ntc_valid || mcu_valid;
}

static uint8_t manual_limit(int16_t temp, uint8_t measured) {
    if (measured)
        return hotspot_manual_limit(temp);
    uint16_t budget = ambient_power_budget(temp);
    for (uint8_t level = WLED_MANUAL_MAX_LEVEL; level; --level) {
        uint16_t mw = level_power_mw(level);
        int16_t predicted = (int16_t)(temp + rise_at_power(mw));
        if (mw <= budget && level <= hotspot_manual_limit(predicted))
            return level;
    }
    return 0u;
}

static uint16_t sos_budget(int16_t temp, uint8_t measured) {
    uint16_t budget = measured ? hotspot_sos_budget(temp) : ambient_power_budget(temp);
    if (budget > WLED_SOS_AVG_MW)
        budget = WLED_SOS_AVG_MW;
    return budget >= SOS_MIN_BUDGET_MW ? budget : 0u;
}

static uint8_t thermal_update(uint32_t now, int16_t temp, uint8_t measured) {
    /* Forecast current steady-state hotspot only in the uncalibrated
     * path. For SOS use the group's average budget, not pulse power.
     * This is not a junction-temperature or transient measurement. */
    uint16_t mw = s_sos ? ((uint32_t)(now - s_sos_at) < s_sos_cycle_ms ? s_sos_budget_mw : 0u) : level_power_mw(s_output_level);
    int16_t predicted = measured ? temp : (int16_t)(temp + rise_at_power(mw));
    if (s_thermal_blocked) {
        if (temp <= s_release_temp)
            s_thermal_blocked = 0u;
        else
            return 0u;
    } else if (predicted >= WLED_STOP_C10) {
        s_thermal_blocked = 1u;
        s_release_temp = measured ? WLED_RESTART_C10 : (int16_t)(temp - WLED_HYST_C10);
        if (s_release_temp > WLED_RESTART_C10)
            s_release_temp = WLED_RESTART_C10;
        s_cap_valid = 0u;
        return 1u;
    }

    if (!s_cap_valid || temp != s_ref_temp || measured != s_ref_measured) {
        s_ref_temp = temp;
        s_ref_measured = measured;
        s_limit_now = manual_limit(temp, measured);
        s_limit_recover = manual_limit((int16_t)(temp + WLED_HYST_C10), measured);
    }
    if (!s_cap_valid || s_limit_now < s_manual_cap) {
        s_manual_cap = s_limit_now;
        s_cap_valid = 1u;
        s_recover_at = now;
    } else if (s_limit_recover > s_manual_cap) {
        if ((uint32_t)(now - s_recover_at) >= WLED_RECOVER_MS) {
            ++s_manual_cap;
            s_recover_at = now;
        }
    } else {
        s_recover_at = now;
    }
    return 0u;
}

static void apply_pwm(uint16_t pwm) {
    if (pwm != s_pwm) {
        WLED_SetPwm(pwm);
        s_pwm = pwm;
    }
}

void WLED_AlgoStop(void) {
    apply_pwm(0u);
    s_step_request = 0;
    s_sos_request = s_sos = 0u;
    s_level = s_output_level = s_active = 0u;
    s_target = 0u;
    s_sos_state = WLED_SOS_OFF;
    s_sos_paused = 0u;
    PowerAlgo_ExtLoadRelease(EXT_LOAD_WLED);
}

uint8_t WLED_AlgoThermalBlocked(void) {
    return s_thermal_blocked;
}

static void wled_protected(void) {
    uint8_t was_sos = s_sos || s_sos_request == 1u;
    WLED_AlgoStop();
    if (was_sos)
        s_sos_state = WLED_SOS_PROTECTED;
}

void WLED_AlgoRequestStep(int8_t step, uint8_t repeat) {
    if (s_sos || s_sos_request == 1u || (repeat && !s_level))
        return;
    if (step > 0 && !repeat)
        s_raise_limit = s_level ? WLED_MANUAL_MAX_LEVEL : WLED_START_PRESS_LIMIT;
    int requested = s_step_request + step;
    if (requested >= -(int)WLED_MANUAL_MAX_LEVEL && requested <= (int)WLED_MANUAL_MAX_LEVEL)
        s_step_request = (int8_t)requested;
}

void WLED_AlgoRequestSOS(uint8_t enable) {
    s_sos_request = enable ? 1u : 2u;
}

uint8_t WLED_AlgoGetOutputPercent(void) {
    unsigned percent = s_output_level * 100u / WLED_MANUAL_MAX_LEVEL;
    return (uint8_t)(percent > 100u ? 100u : percent);
}

static void wled_request(uint32_t now) {
    if (s_sos_request == 2u) {
        s_sos_request = 0u;
        if (s_sos)
            WLED_AlgoStop();
        else
            s_sos_state = WLED_SOS_OFF;
        return;
    }
    if (s_sos_request == 1u) {
        if (s_thermal_blocked) {
            wled_protected();
            return;
        }
        s_sos_request = 0u;
        s_step_request = 0;
        if (s_sos)
            return;
        if (!s_level && !PowerAlgo_ExtLoadRequest(EXT_LOAD_WLED)) {
            s_sos_state = WLED_SOS_PROTECTED;
            return;
        }
        /* Transfer the existing external-load reservation if manual
         * light was already on. Stop its PWM before starting SOS. */
        apply_pwm(0u);
        s_level = s_output_level = 0u;
        s_target = 0u;
        s_sos = 1u;
        s_sos_state = WLED_SOS_WAIT_METER;
        s_wait_at = now;
        return;
    }
    if (!s_step_request || s_sos)
        return;
    if (s_thermal_blocked) {
        s_step_request = 0;
        return;
    }
    int next = (int)s_level + s_step_request;
    if (s_step_request > 0) {
        if (next > s_raise_limit)
            next = s_raise_limit;
        if (next < s_level)
            next = s_level;
    }
    s_step_request = 0;
    if (next < (int)WLED_MIN_LEVEL) {
        WLED_AlgoStop();
        return;
    }
    if (!s_level) {
        if (!PowerAlgo_ExtLoadRequest(EXT_LOAD_WLED)) {
            WLED_AlgoStop();
            return;
        }
        s_wait_at = now;
    }
    s_level = (uint8_t)next;
}

static uint32_t sos_cycle(uint16_t budget) {
    uint32_t cycle = ((uint32_t)WLED_SOS_PEAK_MW * SOS_ON_MS + budget - 1u) / budget;
    return cycle < SOS_MIN_CYCLE_MS ? SOS_MIN_CYCLE_MS : cycle;
}

static uint16_t sos_pwm(uint32_t elapsed) {
    static const uint8_t pulse_start[] = {0, 2, 4, 8, 12, 16, 22, 24, 26};
    unsigned unit = elapsed / SOS_UNIT_MS;
    for (unsigned i = 0u; i < sizeof(pulse_start); ++i) {
        unsigned width = i >= 3u && i < 6u ? 3u : 1u;
        if (unit >= pulse_start[i] && unit < pulse_start[i] + width)
            return WLED_PWM_MAX;
    }
    return 0u;
}

static void sos_begin(uint32_t now, uint16_t budget) {
    s_sos_at = now;
    s_sos_budget_mw = budget;
    s_sos_cycle_ms = sos_cycle(budget);
    s_sos_state = WLED_SOS_TRANSMIT;
}

static void sos_service(uint32_t now, int16_t temp, uint8_t measured) {
    uint16_t budget = sos_budget(temp, measured);
    if (!budget)
        s_sos_paused = 1u;
    else if (s_sos_paused &&
             (measured ? temp <= WLED_RESTART_C10 : sos_budget((int16_t)(temp + WLED_HYST_C10), 0u) != 0u))
        s_sos_paused = 0u;

    if (s_sos_state == WLED_SOS_WAIT_METER) {
        if (!s_sos_paused && (uint32_t)(now - s_sos_at) >= s_sos_cycle_ms)
            sos_begin(now, budget);
        else
            s_sos_state = WLED_SOS_COOLDOWN;
    }
    if (budget && s_sos_budget_mw && budget < s_sos_budget_mw) {
        /* Never shorten the current group's budgeted cooling interval. */
        s_sos_budget_mw = budget;
        uint32_t cycle = sos_cycle(budget);
        if (cycle > s_sos_cycle_ms)
            s_sos_cycle_ms = cycle;
    }

    uint32_t elapsed = now - s_sos_at;
    if (s_sos_paused || elapsed >= SOS_TRANSMIT_MS)
        s_sos_state = WLED_SOS_COOLDOWN;
    if (s_sos_state == WLED_SOS_COOLDOWN && !s_sos_paused &&
        elapsed >= s_sos_cycle_ms) {
        sos_begin(now, budget);
        elapsed = 0u;
    }

    uint16_t pwm = s_sos_state == WLED_SOS_TRANSMIT ? sos_pwm(elapsed) : 0u;
    s_output_level = pwm ? WLED_PEAK_LEVEL : 0u;
    apply_pwm(pwm);
}

wled_sos_state_t WLED_AlgoGetSOSStatus(uint8_t *progress) {
    if (progress) {
        *progress = 0u;
        uint32_t elapsed = Millis() - s_sos_at;
        uint32_t total = 0u;
        if (s_sos_state == WLED_SOS_TRANSMIT)
            total = SOS_TRANSMIT_MS;
        else if (s_sos_state == WLED_SOS_COOLDOWN)
            total = s_sos_cycle_ms > SOS_TRANSMIT_MS ? s_sos_cycle_ms - SOS_TRANSMIT_MS : 0u;
        if (s_sos_state == WLED_SOS_COOLDOWN)
            elapsed = elapsed > SOS_TRANSMIT_MS ? elapsed - SOS_TRANSMIT_MS : 0u;
        if (total)
            *progress = elapsed >= total ? 100u : (uint8_t)(elapsed * 100u / total);
    }
    return s_sos_state;
}

void WLED_AlgoService(uint32_t now) {
    int16_t temp;
    uint8_t measured;
    uint8_t temp_valid = thermal_reference(&temp, &measured);
    if (!s_sos && (uint32_t)(now - s_sos_at) >= s_sos_cycle_ms)
        s_sos_cycle_ms = s_sos_budget_mw = 0u;
    if (temp_valid && thermal_update(now, temp, measured)) {
        uint8_t requested = s_level || s_sos || s_sos_request == 1u || s_step_request > 0;
        wled_protected();
        if (requested)
            PowerAlgo_ReportWLEDOverheat();
        return;
    }
    wled_request(now);
    if (!s_level && !s_sos)
        return;
    ext_load_state_t state = PowerAlgo_ExtLoadState(EXT_LOAD_WLED, now);
    if (state == EXT_LOAD_BLOCKED) {
        wled_protected();
        PowerAlgo_ExtLoadReportBlocked();
        return;
    }
    if (state == EXT_LOAD_WAIT || !temp_valid) {
        if (s_active) {
            apply_pwm(0u);
            s_active = s_output_level = 0u;
            s_target = 0u;
            s_wait_at = now;
            if (s_sos) {
                s_sos_state = WLED_SOS_WAIT_METER;
            }
            PowerAlgo_ExtLoadSetActive(EXT_LOAD_WLED, 0u);
        } else if ((uint32_t)(now - s_wait_at) >= EXT_LOAD_WAIT_MS) {
            wled_protected();
            PowerAlgo_ExtLoadTimeout();
        }
        return;
    }
    if (!s_active) {
        PowerAlgo_ExtLoadSetActive(EXT_LOAD_WLED, 1u);
        s_active = 1u;
    }
    if (s_sos) {
        sos_service(now, temp, measured);
        return;
    }

    uint8_t output = s_level < s_manual_cap ? s_level : s_manual_cap;
    if (!output) {
        wled_protected();
        return;
    }
    uint16_t cap = wled_level_to_pwm(s_manual_cap);
    uint16_t target = wled_level_to_pwm(output);
    if (s_pwm > cap)
        apply_pwm(cap);
    s_output_level = output;
    if (target != s_target) {
        s_ramp_from = s_pwm;
        s_target = target;
        s_ramp_at = now;
    }
    uint32_t elapsed = now - s_ramp_at;
    if (elapsed >= WLED_RAMP_MS) {
        apply_pwm(s_target);
    } else {
        int32_t delta = (int32_t)s_target - s_ramp_from;
        uint16_t pwm = (uint16_t)(s_ramp_from + delta * (int32_t)elapsed / (int32_t)WLED_RAMP_MS);
        apply_pwm(pwm ? pwm : 1u);
    }
}
